/**
 * Build the browser half into the single-file module-loader format.
 *
 * React is taken from the host's module table (`require('react')`), so it is
 * external. Everything else — components, the Markdown renderer, icons, CSS —
 * is bundled. The finished `client.js` is committed with the bundle.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const here = process.cwd()
const checkout = process.env.DSH_CHECKOUT || '/Users/zhaobowen010/MyOwnWorSpace/deepseek-harness'
const pnpmDir = path.join(checkout, 'node_modules', '.pnpm')

async function findEsbuild() {
  const direct = [
    path.join(checkout, 'node_modules', 'esbuild'),
    path.join(here, 'node_modules', 'esbuild'),
  ]
  for (const dir of direct) {
    const entry = path.join(dir, 'lib', 'main.js')
    if (existsSync(entry)) return entry
  }
  if (!existsSync(pnpmDir)) throw new Error(`cannot find pnpm packages under ${pnpmDir}`)
  const candidates = (await readdir(pnpmDir))
    .filter(name => name.startsWith('esbuild@'))
    .sort()
    .reverse()
  for (const name of candidates) {
    const entry = path.join(pnpmDir, name, 'node_modules', 'esbuild', 'lib', 'main.js')
    if (existsSync(entry)) return entry
  }
  throw new Error('cannot find esbuild in the checkout')
}

const esbuildEntry = await findEsbuild()
const { build } = await import(pathToFileURL(esbuildEntry).href)

const result = await build({
  entryPoints: [path.join(here, 'src/client/index.tsx')],
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: ['es2020'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  external: ['react'],
  loader: { '.css': 'text' },
  define: { 'process.env.NODE_ENV': '"production"' },
  write: false,
  minify: false,
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'warning',
})

const code = result.outputFiles[0].text
const pkg = JSON.parse(await readFile(path.join(here, 'package.json'), 'utf8'))
const wrapper = `/* Generated by build.mjs — do not edit by hand. Source: src/client/. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    (function (require, module, exports) {
${code}
    })(require, module, exports);
    return module.exports && module.exports.__esModule && module.exports.default
      ? module.exports.default
      : module.exports;
  },
});
`
await writeFile(path.join(here, 'client.js'), wrapper, 'utf8')
console.log(`client.js written (${(Buffer.byteLength(wrapper) / 1024).toFixed(1)} KiB)`)
